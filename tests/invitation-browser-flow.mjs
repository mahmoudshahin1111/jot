export async function runInvitationBrowserFlow(browser, fixture) {
  const context = await browser.newContext()
  const recipientContext = await browser.newContext()
  const page = await context.newPage()
  const recipientPage = await recipientContext.newPage()
  try {
    page.on('dialog', dialog => dialog.accept())
    await page.goto('http://localhost:5173/login')
    await page.getByLabel('Email', { exact: true }).fill(fixture.email)
    await page.getByLabel('Password', { exact: true }).fill(fixture.password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.waitForURL('**/workspaces')
    await page.goto(`http://localhost:5173/workspaces/${fixture.workspaceId}/settings/users`)
    await page.getByRole('button', { name: 'Invitations 10/10', exact: true }).waitFor()
    if (await page.getByRole('button', { name: 'Invite user', exact: true }).isEnabled()) throw new Error('Invite must be disabled at 10 pending invitations')
    await page.getByRole('button', { name: 'Invitations 10/10', exact: true }).click()
    await page.getByRole('button', { name: /^Remove invitation to / }).first().click()
    await page.getByRole('button', { name: 'Invitations 9/10', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Invite user', exact: true }).click()
    await page.getByLabel('Email', { exact: true }).fill(fixture.recipientEmail)
    await page.getByLabel('Role', { exact: true }).selectOption({ label: 'Editor' })
    await page.getByRole('button', { name: 'Send invitation', exact: true }).click()
    await page.getByRole('button', { name: 'Invitations 10/10', exact: true }).waitFor()
    await page.getByText(`Invitation sent to ${fixture.recipientEmail}. They will join after accepting.`, { exact: true }).waitFor()
    const inbox = await (await context.request.get('http://127.0.0.1:54324/api/v1/messages')).json()
    const mail = inbox.messages.find(message => message.To.some(to => to.Address === fixture.recipientEmail))
    if (!mail) throw new Error('The browser invitation email was not delivered')
    const message = await (await context.request.get(`http://127.0.0.1:54324/api/v1/message/${mail.ID}`)).json()
    const link = message.HTML.match(/href="([^"]+)"/)?.[1]?.replaceAll('&amp;', '&')
    if (!link) throw new Error('The invitation email has no confirmation link')
    await recipientPage.goto(link)
    await recipientPage.getByRole('button', { name: 'Accept invitation', exact: true }).waitFor()
    await recipientPage.getByRole('button', { name: 'Accept invitation', exact: true }).click()
    await recipientPage.waitForURL(`**/workspaces/${fixture.workspaceId}/tasks`)
    await recipientPage.getByRole('link', { name: 'All workspaces', exact: true }).click()
    await recipientPage.getByRole('link', { name: /Open workspace/ }).nth(1).waitFor()
    await recipientPage.goto(`http://localhost:5173/workspaces/${fixture.workspaceId}/dashboard`)
    await recipientPage.getByRole('button', { name: 'Log out', exact: true }).click()
    await recipientPage.waitForURL('**/login')
    await recipientPage.getByRole('button', { name: 'Sign in with email link', exact: true }).click()
    if (await recipientPage.getByLabel('Password', { exact: true }).count()) throw new Error('Email-link login must not require a password')
    await recipientPage.getByLabel('Email', { exact: true }).fill(fixture.recipientEmail)
    await recipientPage.getByRole('button', { name: 'Email me a sign-in link', exact: true }).click()
    await recipientPage.getByText('Check your inbox for a sign-in link to Jot.', { exact: true }).waitFor()
    const loginInbox = await (await recipientContext.request.get('http://127.0.0.1:54324/api/v1/messages')).json()
    const loginMail = loginInbox.messages.find(message => message.ID !== mail.ID && message.To.some(to => to.Address === fixture.recipientEmail))
    if (!loginMail) throw new Error('Email-link login did not send a new email')
    const loginMessage = await (await recipientContext.request.get(`http://127.0.0.1:54324/api/v1/message/${loginMail.ID}`)).json()
    const loginLink = loginMessage.HTML.match(/href="([^"]+)"/)?.[1]?.replaceAll('&amp;', '&')
    if (!loginLink) throw new Error('Login email has no confirmation link')
    await recipientPage.goto(loginLink)
    await recipientPage.waitForURL(url => url.pathname === '/workspaces')
    await recipientPage.getByRole('link', { name: /Open workspace/ }).nth(1).waitFor()
    await page.getByRole('button', { name: 'Invitations 9/10', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Users 2', exact: true }).click()
    await page.getByText(fixture.recipientEmail, { exact: true }).first().waitFor()
    return { limit: 10, capBlocked: true, removalFreedSlot: true, emailDelivered: true, acceptedInBrowser: true, otherWorkspacePreserved: true, acceptedFreedSlotAutomatically: true, emailLinkLogin: true }
  } finally {
    await context.close()
    await recipientContext.close()
  }
}
