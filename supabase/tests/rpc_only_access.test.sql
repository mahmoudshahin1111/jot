begin;
create extension if not exists pgtap with schema extensions;
set local search_path = public, extensions;
select no_plan();

create table public.rpc_default_privileges_test (id bigint generated by default as identity);
create function public.rpc_default_privileges_test() returns integer language sql as $$ select 1 $$;

set local role anon;
select throws_ok(format('select * from public.%I limit 1', tablename),
  '42501', null, 'Anonymous SELECT denied on ' || tablename)
from pg_tables where schemaname = 'public';
select throws_ok(format('insert into public.%I default values', tablename),
  '42501', null, 'Anonymous INSERT denied on ' || tablename)
from pg_tables where schemaname = 'public';
select throws_ok(format('delete from public.%I where false', tablename),
  '42501', null, 'Anonymous DELETE denied on ' || tablename)
from pg_tables where schemaname = 'public';
select throws_ok(format('update public.%I set %I = %I where false', c.relname, a.attname, a.attname),
  '42501', null, 'Anonymous UPDATE denied on ' || c.relname)
from pg_class c join pg_namespace n on n.oid = c.relnamespace
join pg_attribute a on a.attrelid = c.oid and a.attnum = 1
where n.nspname = 'public' and c.relkind in ('r', 'p');

set local role authenticated;
select throws_ok(format('select * from public.%I limit 1', tablename),
  '42501', null, 'Authenticated SELECT denied on ' || tablename)
from pg_tables where schemaname = 'public';
select throws_ok(format('insert into public.%I default values', tablename),
  '42501', null, 'Authenticated INSERT denied on ' || tablename)
from pg_tables where schemaname = 'public';
select throws_ok(format('delete from public.%I where false', tablename),
  '42501', null, 'Authenticated DELETE denied on ' || tablename)
from pg_tables where schemaname = 'public';
select throws_ok(format('update public.%I set %I = %I where false', c.relname, a.attname, a.attname),
  '42501', null, 'Authenticated UPDATE denied on ' || c.relname)
from pg_class c join pg_namespace n on n.oid = c.relnamespace
join pg_attribute a on a.attrelid = c.oid and a.attnum = 1
where n.nspname = 'public' and c.relkind in ('r', 'p');
reset role;

select ok(not has_any_column_privilege(client, c.oid, operation),
  client || ' has no column ' || operation || ' grant on ' || c.relname)
from pg_class c join pg_namespace n on n.oid = c.relnamespace
cross join unnest(array['anon', 'authenticated']) client
cross join unnest(array['SELECT', 'INSERT', 'UPDATE', 'REFERENCES']) operation
where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'f');
select ok(not has_sequence_privilege(client, 'public.rpc_default_privileges_test_id_seq', 'USAGE,SELECT,UPDATE'),
  client || ' cannot access future sequences')
from unnest(array['anon', 'authenticated']) client;
select ok(not has_function_privilege(client, 'public.rpc_default_privileges_test()', 'EXECUTE'),
  client || ' cannot execute future RPCs without an explicit grant')
from unnest(array['anon', 'authenticated']) client;
select ok(has_table_privilege('service_role', c.oid, operation),
  'Trusted service retains ' || operation || ' on ' || c.relname)
from pg_class c join pg_namespace n on n.oid = c.relnamespace
cross join unnest(array['SELECT', 'INSERT', 'UPDATE', 'DELETE']) operation
where n.nspname = 'public' and c.relkind in ('r', 'p');
select ok(not has_schema_privilege(client, 'public', 'CREATE'), client || ' cannot create public objects')
from unnest(array['anon', 'authenticated']) client;
select * from finish();
rollback;
